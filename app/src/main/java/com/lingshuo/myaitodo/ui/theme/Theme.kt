/**
 * App theme.
 *
 * Colours are derived from the user's wallpaper on Android 12+ (dynamic colour);
 * older devices fall back to the baseline violet/teal palette above. Nothing in
 * the UI hardcodes hex values, so the app always matches the system palette.
 */
@Composable
fun MyAiTodoTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val context = LocalContext.current
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ->
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)

        darkTheme -> FallbackDarkColorScheme
        else -> FallbackLightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content,
    )
}
